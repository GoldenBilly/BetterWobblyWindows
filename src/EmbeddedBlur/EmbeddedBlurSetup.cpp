void WobblyWindowsEffect::InitEmbeddedBlurStrengthValues()
{
    _embeddedBlurOffsets.clear();
    _embeddedBlurStrengthValues.clear();

    // Same dual-kawase strength table shape as Better Blur DX.
    _embeddedBlurOffsets.push_back({1.0f, 2.0f, 10});
    _embeddedBlurOffsets.push_back({2.0f, 3.0f, 20});
    _embeddedBlurOffsets.push_back({2.0f, 5.0f, 50});
    _embeddedBlurOffsets.push_back({3.0f, 8.0f, 150});

    constexpr int blurStrengthStepCount = BetterWobblyWindows::BlurStrengthStepCount;
    int remainingSteps = blurStrengthStepCount;
    float offsetSum = 0.0f;
    for (const BlurOffset &offset : _embeddedBlurOffsets) {
        offsetSum += offset.maxOffset - offset.minOffset;
    }

    for (int i = 0; i < static_cast<int>(_embeddedBlurOffsets.size()); ++i) {
        int iterationNumber = std::ceil((_embeddedBlurOffsets[i].maxOffset - _embeddedBlurOffsets[i].minOffset) /
            offsetSum * blurStrengthStepCount);
        remainingSteps -= iterationNumber;
        if (remainingSteps < 0) {
            iterationNumber += remainingSteps;
        }

        const float offsetDifference = _embeddedBlurOffsets[i].maxOffset - _embeddedBlurOffsets[i].minOffset;
        for (int j = 1; j <= iterationNumber; ++j) {
            _embeddedBlurStrengthValues.push_back({i + 1,
                _embeddedBlurOffsets[i].minOffset +
                    (offsetDifference / static_cast<float>(iterationNumber)) * static_cast<float>(j)});
        }
    }
}

void WobblyWindowsEffect::InitEmbeddedBlur()
{
    // The resource init function is generated by rcc in the global namespace.
    // Calling Q_INIT_RESOURCE() from inside namespace KWin resolves to the wrong
    // symbol on some builds, so call the global function explicitly. This makes
    // shader loading deterministic for externally loaded effect plugins.
    ::qInitResources_wobblyblur();

#ifdef BETTER_WOBBLY_USE_CORE_SHADERS
    const auto vertexShaderPath = QStringLiteral(":/effects/wobblywindows/shaders/vertex_core.vert");
    const auto downsampleShaderPath = QStringLiteral(":/effects/wobblywindows/shaders/downsample_core.frag");
    const auto upsampleShaderPath = QStringLiteral(":/effects/wobblywindows/shaders/upsample_core.frag");
    const auto onscreenShaderPath = QStringLiteral(":/effects/wobblywindows/shaders/onscreen_core.frag");
    const auto compositeShaderPath = QStringLiteral(":/effects/wobblywindows/shaders/composite_core.frag");
    const auto noiseShaderPath = QStringLiteral(":/effects/wobblywindows/shaders/noise_core.frag");
    constexpr auto shaderProfileName = "core";
#else
    const auto vertexShaderPath = QStringLiteral(":/effects/wobblywindows/shaders/vertex.vert");
    const auto downsampleShaderPath = QStringLiteral(":/effects/wobblywindows/shaders/downsample.frag");
    const auto upsampleShaderPath = QStringLiteral(":/effects/wobblywindows/shaders/upsample.frag");
    const auto onscreenShaderPath = QStringLiteral(":/effects/wobblywindows/shaders/onscreen.frag");
    const auto compositeShaderPath = QStringLiteral(":/effects/wobblywindows/shaders/composite.frag");
    const auto noiseShaderPath = QStringLiteral(":/effects/wobblywindows/shaders/noise.frag");
    constexpr auto shaderProfileName = "compatibility";
#endif

    _embeddedDownsamplePass.shader = ShaderManager::instance()->generateShaderFromFile(ShaderTrait::MapTexture,
        vertexShaderPath,
        downsampleShaderPath);
    _embeddedUpsamplePass.shader = ShaderManager::instance()->generateShaderFromFile(ShaderTrait::MapTexture,
        vertexShaderPath,
        upsampleShaderPath);
    _embeddedOnscreenPass.shader = ShaderManager::instance()->generateShaderFromFile(ShaderTrait::MapTexture,
        vertexShaderPath,
        onscreenShaderPath);
    _embeddedCompositePass.shader = ShaderManager::instance()->generateShaderFromFile(ShaderTrait::MapTexture,
        vertexShaderPath,
        compositeShaderPath);
    _embeddedNoisePass.shader =
        ShaderManager::instance()->generateShaderFromFile(ShaderTrait::MapTexture, vertexShaderPath, noiseShaderPath);

    if (!_embeddedDownsamplePass.shader || !_embeddedUpsamplePass.shader || !_embeddedOnscreenPass.shader ||
        !_embeddedCompositePass.shader) {
        BetterWobblyWindows::WriteKernelLogLine(
            QStringLiteral("embedded blur %1 shader initialization failed").arg(QString::fromLatin1(shaderProfileName)),
            BetterWobblyWindows::KernelLogPriority::Error);
        BetterWobblyWindows::WriteBlurTraceLine(
            QStringLiteral("shader init FAILED profile=%1 downsampleExists=%2 upsampleExists=%3 onscreenExists=%4")
                .arg(QString::fromLatin1(shaderProfileName))
                .arg(QFile::exists(downsampleShaderPath))
                .arg(QFile::exists(upsampleShaderPath))
                .arg(QFile::exists(onscreenShaderPath)));
        qCWarning(KWIN_WOBBLYWINDOWS) << "Embedded DX blur shader initialization failed"
                                      << "profile:" << shaderProfileName
                                      << "downsample exists:" << QFile::exists(downsampleShaderPath)
                                      << "upsample exists:" << QFile::exists(upsampleShaderPath)
                                      << "onscreen exists:" << QFile::exists(onscreenShaderPath);
        _embeddedBlurValid = false;
        return;
    }

    _embeddedDownsamplePass.mvpMatrixLocation =
        _embeddedDownsamplePass.shader->uniformLocation("modelViewProjectionMatrix");
    _embeddedDownsamplePass.offsetLocation = _embeddedDownsamplePass.shader->uniformLocation("offset");
    _embeddedDownsamplePass.halfpixelLocation = _embeddedDownsamplePass.shader->uniformLocation("halfpixel");
    _embeddedDownsamplePass.sourceClampLocation = _embeddedDownsamplePass.shader->uniformLocation("sourceClamp");

    _embeddedUpsamplePass.mvpMatrixLocation =
        _embeddedUpsamplePass.shader->uniformLocation("modelViewProjectionMatrix");
    _embeddedUpsamplePass.offsetLocation = _embeddedUpsamplePass.shader->uniformLocation("offset");
    _embeddedUpsamplePass.halfpixelLocation = _embeddedUpsamplePass.shader->uniformLocation("halfpixel");
    _embeddedUpsamplePass.sourceClampLocation = _embeddedUpsamplePass.shader->uniformLocation("sourceClamp");

    _embeddedOnscreenPass.mvpMatrixLocation =
        _embeddedOnscreenPass.shader->uniformLocation("modelViewProjectionMatrix");
    _embeddedOnscreenPass.colorMatrixLocation = _embeddedOnscreenPass.shader->uniformLocation("colorMatrix");
    _embeddedOnscreenPass.offsetLocation = _embeddedOnscreenPass.shader->uniformLocation("offset");
    _embeddedOnscreenPass.halfpixelLocation = _embeddedOnscreenPass.shader->uniformLocation("halfpixel");
    _embeddedOnscreenPass.boxLocation = _embeddedOnscreenPass.shader->uniformLocation("box");
    _embeddedOnscreenPass.cornerRadiusLocation = _embeddedOnscreenPass.shader->uniformLocation("cornerRadius");
    _embeddedOnscreenPass.opacityLocation = _embeddedOnscreenPass.shader->uniformLocation("opacity");
    _embeddedOnscreenPass.textureSizeLocation = _embeddedOnscreenPass.shader->uniformLocation("textureSize");
    _embeddedOnscreenPass.sourceClampLocation = _embeddedOnscreenPass.shader->uniformLocation("sourceClamp");
    _embeddedOnscreenPass.edgeSoftnessLocation = _embeddedOnscreenPass.shader->uniformLocation("edgeSoftness");
    _embeddedOnscreenPass.sourceYFlipLocation = _embeddedOnscreenPass.shader->uniformLocation("sourceYFlip");
    _embeddedOnscreenPass.refractionEnabledLocation =
        _embeddedOnscreenPass.shader->uniformLocation("refractionEnabled");
    _embeddedOnscreenPass.refractionRectSizeLocation =
        _embeddedOnscreenPass.shader->uniformLocation("refractionRectSize");
    _embeddedOnscreenPass.refractionEdgeSizePixelsLocation =
        _embeddedOnscreenPass.shader->uniformLocation("refractionEdgeSizePixels");
    _embeddedOnscreenPass.refractionCornerRadiusPixelsLocation =
        _embeddedOnscreenPass.shader->uniformLocation("refractionCornerRadiusPixels");
    _embeddedOnscreenPass.refractionStrengthLocation =
        _embeddedOnscreenPass.shader->uniformLocation("refractionStrength");
    _embeddedOnscreenPass.refractionNormalPowLocation =
        _embeddedOnscreenPass.shader->uniformLocation("refractionNormalPow");
    _embeddedOnscreenPass.refractionRgbFringingLocation =
        _embeddedOnscreenPass.shader->uniformLocation("refractionRGBFringing");
    _embeddedOnscreenPass.refractionTextureRepeatModeLocation =
        _embeddedOnscreenPass.shader->uniformLocation("refractionTextureRepeatMode");
    _embeddedOnscreenPass.refractionModeLocation = _embeddedOnscreenPass.shader->uniformLocation("refractionMode");

    _embeddedCompositePass.mvpMatrixLocation =
        _embeddedCompositePass.shader->uniformLocation("modelViewProjectionMatrix");
    _embeddedCompositePass.boxLocation = _embeddedCompositePass.shader->uniformLocation("box");
    _embeddedCompositePass.cornerRadiusLocation = _embeddedCompositePass.shader->uniformLocation("cornerRadius");
    _embeddedCompositePass.opacityLocation = _embeddedCompositePass.shader->uniformLocation("opacity");
    _embeddedCompositePass.textureSizeLocation = _embeddedCompositePass.shader->uniformLocation("textureSize");
    _embeddedCompositePass.sourceClampLocation = _embeddedCompositePass.shader->uniformLocation("sourceClamp");
    _embeddedCompositePass.edgeSoftnessLocation = _embeddedCompositePass.shader->uniformLocation("edgeSoftness");
    _embeddedCompositePass.sourceYFlipLocation = _embeddedCompositePass.shader->uniformLocation("sourceYFlip");

    if (_embeddedNoisePass.shader) {
        _embeddedNoisePass.mvpMatrixLocation = _embeddedNoisePass.shader->uniformLocation("modelViewProjectionMatrix");
        _embeddedNoisePass.noiseTextureSizeLocation = _embeddedNoisePass.shader->uniformLocation("noiseTextureSize");
        _embeddedNoisePass.blurTextureSizeLocation = _embeddedNoisePass.shader->uniformLocation("blurTextureSize");
        _embeddedNoisePass.renderScaleLocation = _embeddedNoisePass.shader->uniformLocation("renderScale");
        _embeddedNoisePass.boxLocation = _embeddedNoisePass.shader->uniformLocation("box");
        _embeddedNoisePass.cornerRadiusLocation = _embeddedNoisePass.shader->uniformLocation("cornerRadius");
        _embeddedNoisePass.opacityLocation = _embeddedNoisePass.shader->uniformLocation("opacity");
        _embeddedNoisePass.noiseModeLocation = _embeddedNoisePass.shader->uniformLocation("noiseMode");
    } else {
        qCWarning(KWIN_WOBBLYWINDOWS) << "Embedded DX blur noise shader initialization failed";
    }

    _embeddedBlurValid = true;
    if (BetterWobblyWindows::IsBlurTraceEnabled()) {
        BetterWobblyWindows::WriteBlurTraceLine(
            QStringLiteral("embedded-blur init OK profile=%1 downsampleMvp=%2 upsampleMvp=%3 onscreenMvp=%4")
                .arg(QString::fromLatin1(shaderProfileName))
                .arg(_embeddedDownsamplePass.mvpMatrixLocation)
                .arg(_embeddedUpsamplePass.mvpMatrixLocation)
                .arg(_embeddedOnscreenPass.mvpMatrixLocation));
        qCWarning(KWIN_WOBBLYWINDOWS) << "embedded-blur init OK"
                                      << "profile" << shaderProfileName << "downsample"
                                      << _embeddedDownsamplePass.mvpMatrixLocation << "upsample"
                                      << _embeddedUpsamplePass.mvpMatrixLocation << "onscreen"
                                      << _embeddedOnscreenPass.mvpMatrixLocation;
    }
}

void WobblyWindowsEffect::ReconfigureEmbeddedBlur()
{
    const int previousIterationCount = _embeddedBlurIterationCount;
    const int previousExpandSize = _embeddedBlurExpandSize;
    const int previousNoiseStrength = _embeddedBlurNoiseStrength;

    const KConfigGroup betterWobblyGroup(effects->config(), BetterWobblyWindows::BetterWobblyConfigGroupName);

    _embeddedBlurEnabled = betterWobblyGroup.readEntry("EmbeddedDXBlur", true);
    _embeddedBlurFallbackEnabled = !betterWobblyGroup.readEntry("EmbeddedDXBlurApiOnly", false);
    _embeddedBlurUseBetterBlurDXSettings = BetterWobblyWindows::UseBetterBlurDxSettings(effects->config());
    const BetterWobblyWindows::DxBlurVisualSettings blurSettings =
        BetterWobblyWindows::ReadEmbeddedBlurEffectiveSettings(effects->config());

    int blurStrength = blurSettings.blurStrength;
    blurStrength = std::clamp(blurStrength,
        BetterWobblyWindows::MinimumBlurStrength,
        static_cast<int>(_embeddedBlurStrengthValues.size()));

    const auto &[iteration, offset] = _embeddedBlurStrengthValues[blurStrength - 1];
    _embeddedBlurIterationCount = iteration;
    _embeddedBlurOffset = offset;
    _embeddedBlurExpandSize = _embeddedBlurOffsets[_embeddedBlurIterationCount - 1].expandSize;

    _embeddedBlurColorMode = std::clamp(betterWobblyGroup.readEntry("EmbeddedDXBlurColorMode", 0),
        BetterWobblyWindows::MinimumBlurMode,
        BetterWobblyWindows::MaximumColorMode);
    _embeddedBlurNoiseMode = std::clamp(betterWobblyGroup.readEntry("EmbeddedDXBlurNoiseMode", 0),
        BetterWobblyWindows::MinimumBlurMode,
        BetterWobblyWindows::MaximumNoiseMode);
    const int configuredTransitionFrames =
        betterWobblyGroup.readEntry("EmbeddedDXBlurHandoffFrames", BetterWobblyWindows::DefaultHandoffFrames);
    _embeddedBlurHandoffFrames = std::clamp(configuredTransitionFrames <= 0 ? BetterWobblyWindows::DefaultHandoffFrames
                                                                            : configuredTransitionFrames,
        BetterWobblyWindows::MinimumHandoffFrames,
        BetterWobblyWindows::MaximumHandoffFrames);
    _embeddedBlurEdgeSoftnessPixels = std::clamp(betterWobblyGroup.readEntry("EmbeddedDXBlurEdgeSoftnessPixels", 0),
        BetterWobblyWindows::MinimumEdgeSoftnessPixels,
        BetterWobblyWindows::MaximumEdgeSoftnessPixels);
    _embeddedBlurClearIntermediateTargets =
        betterWobblyGroup.readEntry("EmbeddedDXBlurClearIntermediateTargets", false);
    _embeddedBlurFallbackFrames = std::clamp(
        betterWobblyGroup.readEntry("EmbeddedDXBlurFallbackFrames", BetterWobblyWindows::DefaultFallbackFrames),
        BetterWobblyWindows::MinimumFallbackFrames,
        BetterWobblyWindows::MaximumFallbackFrames);
    _embeddedBlurSourceYFlip =
        betterWobblyGroup.readEntry("EmbeddedDXBlurSourceYFlip", BetterWobblyWindows::DefaultSourceYFlip);
    _maxPhysicsStepsPerFrame = std::clamp(
        betterWobblyGroup.readEntry("MaxPhysicsStepsPerFrame", BetterWobblyWindows::DefaultPhysicsStepsPerFrame),
        BetterWobblyWindows::MinimumPhysicsStepsPerFrame,
        BetterWobblyWindows::MaximumPhysicsStepsPerFrame);

    const qreal rawSaturation = blurSettings.saturation / BetterWobblyWindows::PercentScale;
    const qreal rawContrast = blurSettings.contrast / BetterWobblyWindows::PercentScale;
    const qreal rawBrightness = blurSettings.brightness / BetterWobblyWindows::PercentScale;

    // Mode 0 is the unmodified Better Blur DX path. Do not silently clamp
    // values read from its config; the reference feeds them straight into the
    // color transform matrix.
    qreal saturation = rawSaturation;
    qreal contrast = rawContrast;
    qreal brightness = rawBrightness;
    if (_embeddedBlurColorMode == 1) {
        // Anti-flash/safe hand-off variant: never boost already-corrected pixels.
        saturation = std::clamp(saturation, 0.0, 1.0);
        contrast = std::clamp(contrast, 0.0, 1.0);
        brightness = std::clamp(brightness, 0.0, 1.0);
    } else if (_embeddedBlurColorMode == 2) {
        // Diagnostic variant: use the blur kernel without a color matrix.
        saturation = contrast = brightness = 1.0;
    }
    _embeddedBlurColorMatrix = BetterWobblyWindows::BuildColorTransformMatrix(saturation, contrast, brightness);
    _embeddedBlurNoiseStrength = std::clamp(blurSettings.noiseStrength,
        BetterWobblyWindows::MinimumNoiseStrength,
        BetterWobblyWindows::MaximumNoiseStrength);
    _embeddedBlurCornerRadius =
        std::max(static_cast<qreal>(BetterWobblyWindows::MinimumCornerRadius), blurSettings.cornerRadius);

    // These conversions intentionally mirror RefractionPass::reconfigure() in
    // Better Blur DX snapshot 3545101. Keeping the raw config values here would
    // make the same KCM settings produce a different material while dragging.
    _embeddedRefractionEnabled = blurSettings.refractionStrength > 0;
    _embeddedRefractionEdgeSizePixels = static_cast<qreal>(blurSettings.refractionEdgeSize) * 10.0;
    constexpr qreal refractionCornerStep = 200.0 / 30.0;
    _embeddedRefractionCornerRadiusPixels =
        std::round(static_cast<qreal>(blurSettings.refractionCornerRadius) / refractionCornerStep) *
        refractionCornerStep;
    _embeddedRefractionStrength = static_cast<qreal>(blurSettings.refractionStrength) / 30.0;
    _embeddedRefractionNormalPow = static_cast<qreal>(blurSettings.refractionNormalPow) * 0.5;
    _embeddedRefractionRgbFringing = static_cast<qreal>(blurSettings.refractionRgbFringing) / 30.0;
    _embeddedRefractionTextureRepeatMode = blurSettings.refractionTextureRepeatMode;
    _embeddedRefractionMode = blurSettings.refractionMode;

    _embeddedBlurRenderData.clear();
    const bool mustReleasePool = !_embeddedBlurEnabled || !_embeddedBlurFallbackEnabled || !_embeddedBlurValid ||
        _embeddedBlurIterationCount < previousIterationCount || _embeddedBlurExpandSize < previousExpandSize;
    if (mustReleasePool) {
        ReleaseEmbeddedBlurRenderTargets(_embeddedBlurReusableRenderData);
    } else {
        _embeddedBlurReusableRenderData.hasValidSource = false;
        _embeddedBlurReusableRenderData.lastSourceWasClipped = false;
        _embeddedBlurReusableRenderData.lastRenderRect = QRect();
        _embeddedBlurReusableRenderData.lastRenderScale = 0.0;
        _embeddedBlurReusableRenderData.fallbackFramesRemaining = 0;
        _embeddedBlurReusableRenderData.lastSourceWindow = nullptr;
    }

    if (!_embeddedBlurEnabled || _embeddedBlurNoiseStrength <= 0 ||
        _embeddedBlurNoiseStrength != previousNoiseStrength) {
        _embeddedNoisePass.noiseTexture.reset();
        _embeddedNoisePass.noiseTextureScale = 0.0;
        _embeddedNoisePass.noiseTextureStrength = -1;
    }

    if (BetterWobblyWindows::IsBlurTraceEnabled()) {
        BetterWobblyWindows::WriteBlurTraceLine(
            QStringLiteral("embedded-blur config enabled=%1 valid=%2 useDxSettings=%3 strength=%4 saturation=%5 "
                           "contrast=%6 brightness=%7 iterations=%8 offset=%9 expand=%10 noise=%11 cornerRadius=%12 "
                           "colorMode=%13 noiseMode=%14 handoffFrames=%15 edgeSoftness=%16 clearIntermediates=%17 "
                           "fallbackFrames=%18 sourceYFlip=%19 suppressExternal=%20 maxPhysicsSteps=%21")
                .arg(_embeddedBlurEnabled)
                .arg(_embeddedBlurValid)
                .arg(_embeddedBlurUseBetterBlurDXSettings)
                .arg(blurStrength)
                .arg(blurSettings.saturation)
                .arg(blurSettings.contrast)
                .arg(blurSettings.brightness)
                .arg(_embeddedBlurIterationCount)
                .arg(_embeddedBlurOffset)
                .arg(_embeddedBlurExpandSize)
                .arg(_embeddedBlurNoiseStrength)
                .arg(_embeddedBlurCornerRadius)
                .arg(_embeddedBlurColorMode)
                .arg(_embeddedBlurNoiseMode)
                .arg(_embeddedBlurHandoffFrames)
                .arg(_embeddedBlurEdgeSoftnessPixels)
                .arg(_embeddedBlurClearIntermediateTargets)
                .arg(_embeddedBlurFallbackFrames)
                .arg(_embeddedBlurSourceYFlip)
                .arg(_maxPhysicsStepsPerFrame));
        qCWarning(KWIN_WOBBLYWINDOWS) << "embedded-blur config"
                                      << "enabled" << _embeddedBlurEnabled << "valid" << _embeddedBlurValid
                                      << "useDxSettings" << _embeddedBlurUseBetterBlurDXSettings << "strength"
                                      << blurStrength << "saturation" << blurSettings.saturation << "contrast"
                                      << blurSettings.contrast << "brightness" << blurSettings.brightness
                                      << "iterations" << _embeddedBlurIterationCount << "offset" << _embeddedBlurOffset
                                      << "expand" << _embeddedBlurExpandSize << "noise" << _embeddedBlurNoiseStrength
                                      << "cornerRadius" << _embeddedBlurCornerRadius << "colorMode"
                                      << _embeddedBlurColorMode << "noiseMode" << _embeddedBlurNoiseMode
                                      << "handoffFrames" << _embeddedBlurHandoffFrames << "edgeSoftness"
                                      << _embeddedBlurEdgeSoftnessPixels << "clearIntermediates"
                                      << _embeddedBlurClearIntermediateTargets << "fallbackFrames"
                                      << _embeddedBlurFallbackFrames << "sourceYFlip" << _embeddedBlurSourceYFlip
                                      << "maxPhysicsSteps" << _maxPhysicsStepsPerFrame;
    }
}

